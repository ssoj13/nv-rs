//! Authoritative NVENC codec, profile, and preset GUIDs from `nvEncodeAPI.h`.
//!
//! **What.** Defines [`sys::GUID`] constants for codecs (H.264, HEVC, AV1), codec profiles, and
//! presets (`P1`–`P7`) because `nvEncodeAPI.h` declares them as `static const GUID` variables that
//! bindgen does not emit as Rust constants.
//! **Used by** [`crate`] for session initialization, preset queries, and capability checks.

use nvenc_sys as sys;

/// Helper to construct a [`sys::GUID`] at compile time.
pub const fn guid(d1: u32, d2: u16, d3: u16, d4: [u8; 8]) -> sys::GUID {
    sys::GUID {
        Data1: d1,
        Data2: d2,
        Data3: d3,
        Data4: d4,
    }
}

